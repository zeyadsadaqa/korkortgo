"""Compile complete approved teaching for isolated 9L views; does not activate the package."""
import argparse
import hashlib,json,struct
from pathlib import Path
from build_navigation import SharedEmitter, read, ROOT, DEST
from content_schema import Schema

def generate():
    c=read(Path('content/curriculum.json'))
    emitter=SharedEmitter(Schema(ROOT),'reader')
    fields=[('readerModules',c['modules'],'List<CurriculumModule>'),('readerDocuments',c['documents'],'List<CurriculumDocument>'),('readerOrder',c['reading_order'],'List<ContentId>'),('readerTags',c['lesson_category_tags'],'Map<ContentId, Set<Category>>'),('readerAssets',c['assets'],'List<CurriculumAsset>')]
    calls=[(name,kind,emitter.emit(value,kind,name)) for name,value,kind in fields]
    header='// Generated by tools/build_reader.py; do not edit.\npackage se.korkort\n\n'
    files={DEST/'GeneratedReader.kt':header+''.join(f'internal val {name}: {kind} by lazy {{ {call} }}\n' for name,kind,call in calls)}
    dimensions=[]
    for asset in c['assets']:
        if asset['kind']!='contextual_illustration':continue
        data=(ROOT/asset['bundled']['path']).read_bytes()
        assert hashlib.sha256(data).hexdigest()==asset['bundled']['sha256']
        assert data[:8]==b'\x89PNG\r\n\x1a\n'
        width,height=struct.unpack('>II',data[16:24])
        dimensions.append('AssetId('+json.dumps(asset['id'])+') to ('+str(width)+' to '+str(height)+')')
    files[DEST/'GeneratedReader.kt']+='internal val readerImageDimensions: Map<AssetId, Pair<Int, Int>> by lazy { mapOf('+', '.join(dimensions)+') }\n'

    for i in range(0,len(emitter.functions),150):
        files[DEST/f'GeneratedReaderPart{i//150:03}.kt']=header+''.join(f'internal fun {fn}(): {kind} = {expr}\n' for fn,kind,expr in emitter.functions[i:i+150])
    values={'modules':c['modules'],'documents':c['documents'],'reading_order':c['reading_order'],'lesson_category_tags':c['lesson_category_tags'],'assets':c['assets']}
    parity=''.join(name+'\t'+hashlib.sha256(json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()).hexdigest()+'\n' for name,value in values.items())
    files[Path('docs/curriculum/app-migration/implementation-evidence/9L/reader-parity.tsv')]=parity
    return files

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();files=generate()
    for path,value in files.items():
        if args.check: assert (ROOT/path).read_text()==value,path
        else:
            (ROOT/path).parent.mkdir(parents=True,exist_ok=True)
            (ROOT/path).write_text(value)
    print(f'Complete reader: {len(files)-1} Kotlin files plus parity receipt; no route or eligibility activation.')
if __name__=='__main__':main()
