"""Generate unscored 9F renderer fixtures only; never apply held replacements to the bank."""
import argparse,json
from pathlib import Path
from compile_curriculum import kotlin_string as q
ROOT=Path(__file__).resolve().parent.parent
CODES=[f'S{n}' for n in range(1,14)]+['T1','T2','T6','T8','T22','X8']
DEST=Path('composeApp/src/verificationCommonMain/kotlin/se/korkort/DeliveryCandidates.kt')
def read(p):return json.loads((ROOT/p).read_text())
def output():
    actions={a['question_id']:a for a in read(Path('docs/curriculum/app-migration/question-actions.json'))['questions']}
    descriptions={r['question_id']:r for n in range(3,16) for r in read(Path(f'docs/curriculum/app-migration/implementation-evidence/9D{n}/description-acceptance.json'))['questions']}
    assets={a['original']['sha256']:a for a in read(Path('content/curriculum.json'))['assets']};lines=[]
    def image(record):
        asset=assets[record['asset']['sha256']]
        return 'AssessmentImagePresentation(AssetId('+q(asset['id'])+'), '+q(record['description'])+')'
    for code in CODES:
        for direction in ['meaning','recognise']:
            id=f'sign-{direction}-{code}';a=actions[id];p=a['proposed_changes'];d=descriptions[id];assert a['disposition']=='replace' and d['description_result']=='accepted'
            stem=image(next(i for i in d['images'] if i['slot']=='stem')) if direction=='meaning' else 'null'
            options=[]
            for n,o in enumerate(p['options']):
                picture=image(next(i for i in d['images'] if i['slot']==o['option_id'])) if direction=='recognise' else 'null'
                options.append('AssessmentChoicePresentation(OptionId('+q(o['option_id'])+'), '+q(chr(65+n))+', '+q(o['meaning_option_text'] or '')+', '+picture+', false, null, null)')
            lines.append(q(code+'/'+direction)+' -> AssessmentPresentation(QuestionRevisionKey(QuestionId('+q(id)+'), SemanticRevision("delivery-fixture-r1")), '+q(p['prompt'])+', '+stem+', listOf('+', '.join(options)+'), true, null, null, null)')
    return '// Generated by tools/prepare_delivery_fixtures.py; unscored, verification builds only.\npackage se.korkort\n\ninternal val deliveryFixtureCodes=listOf('+', '.join(q(c) for c in CODES)+')\ninternal fun deliveryCandidate(code: String, direction: String): AssessmentPresentation = when(code+"/"+direction) {\n'+''.join('    '+s+'\n' for s in lines)+'    else -> error("Unknown verification fixture")\n}\n'
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();value=output()
    held=Path('composeApp/src/commonMain/kotlin/se/korkort/ReplacementDeliveryHolds.kt')
    ids=[f'sign-{direction}-{code}' for code in CODES for direction in ['meaning','recognise']]
    holds='// Generated by tools/prepare_delivery_fixtures.py from exact 7D replacement identities.\npackage se.korkort\ninternal val replacementDeliveryHolds: Set<QuestionId> = setOf('+', '.join('QuestionId('+q(id)+')' for id in ids)+')\n'
    for path,data in {DEST:value,held:holds}.items():
        if args.check:assert (ROOT/path).read_text()==data,path
        else:(ROOT/path).write_text(data)
if __name__=='__main__':main()
