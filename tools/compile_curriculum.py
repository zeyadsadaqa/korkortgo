def kotlin_string(value):
    def quote(s):
        return json.dumps(s,ensure_ascii=False).replace('$','\\$').replace('\\f','\\u000c')
    if len(value)<=4000:return quote(value)
    return 'listOf('+', '.join(quote(value[i:i+4000]) for i in range(0,len(value),4000))+').joinToString("")'


class Emitter:
    def __init__(self,schema,symbol):
        self.schema,self.symbol=schema,symbol
        self.functions=[]
        self.trace=[]

    def function(self,kind,expression,path,origin):
        name=f'{self.symbol}Node{len(self.functions):06}'
        self.functions.append((name,kind,expression))
        self.trace.append({'symbol':name,'input':path,'origin':origin})
        return name+'()'

    def emit(self,value,kind,path,origin=None):
        kind=self.schema.aliases.get(kind,kind)
        if value is None:return 'null'
        if kind.endswith('?'):return self.emit(value,kind[:-1],path,origin)
        if '<' in kind:
            outer,args=self.schema.generic(kind)
            if outer=='Map':
                terms=[self.emit(k,args[0],path+'/key',origin)+' to '+self.emit(value[k],args[1],path+'/'+k,origin) for k in sorted(value)]
                if len(terms)>20:
                    chunks=[self.function(kind,'mapOf('+', '.join(terms[i:i+20])+')',path,origin) for i in range(0,len(terms),20)]
                    return self.function(kind,' + '.join(chunks),path,origin)
                return 'mapOf('+', '.join(terms)+')'
            terms=[self.emit(x,args[0],path+f'/{i}',origin) for i,x in enumerate(value)]
            if len(terms)>20:
                chunks=[self.function(kind,('setOf' if outer=='Set' else 'listOf')+'('+', '.join(terms[i:i+20])+')',path,origin) for i in range(0,len(terms),20)]
                return self.function(kind,' + '.join(chunks),path,origin)
            return ('setOf' if outer=='Set' else 'listOf')+'('+', '.join(terms)+')'
        if kind=='String':return kotlin_string(value)
        if kind in self.schema.wrappers:return kind+'('+kotlin_string(value)+')'
        if kind=='Int':return str(value)
        if kind=='Boolean':return str(value).lower()
        if kind in self.schema.enums:return kind+'.'+self.schema.enums[kind][value]
        target=self.schema.unions[kind][value['type']] if kind in self.schema.unions else kind
        origin=value.get('origin',value.get('metadata',{}).get('origin',origin))
        terms=[camel+' = '+self.emit(value[field],typ,path+'/'+field,origin) for field,camel,typ in self.schema.classes[target]]
        return self.function(target,target+'('+', '.join(terms)+')',path,origin)

    def render(self,package,paths):
        terms=[]
        for field,camel,kind in self.schema.classes['CurriculumPackage']:
            terms.append(camel+' = '+self.emit(package[field],kind,paths[field]))
        files={'GeneratedCurriculum.kt':MARKER+'package se.korkort\n\n'+f'internal val {self.symbol}: CurriculumPackage by lazy {{\n    CurriculumPackage('+', '.join(terms)+')\n}\n'}
        for start in range(0,len(self.functions),40):
            name=f'GeneratedCurriculumPart{start//40:04}.kt'
            lines=[MARKER.rstrip(),'package se.korkort','']
            for offset,(fn,kind,expression) in enumerate(self.functions[start:start+40]):
                lines.append(f'internal fun {fn}(): {kind} = {expression}')
                self.trace[start+offset].update({'output_file':name,'output_line':len(lines)})
            files[name]='\n'.join(lines)+'\n'
        return files


def compile_files(paths,manifest_path,output_dir,trace_path,profile='fixture',symbol='generatedCurriculum',root=ROOT,source_authority=AUTHORITY):
    root=root.resolve()
    inputs={k:Path(v).resolve() for k,v in paths.items()}
    if set(inputs)!=set(ROOT_TYPES):fail('inputs','four explicit authoring inputs required')
    manifest_path=Path(manifest_path).resolve()
    if not manifest_path.is_relative_to(root):fail('manifest','manifest must be inside the repository root')
    output_dir=Path(output_dir).resolve();trace_path=Path(trace_path).resolve()
    if not re.fullmatch('[a-z][A-Za-z0-9_]*',symbol):fail('symbol','expected lower-camel Kotlin identifier')
    protected=[root/'content',root/'composeApp/src',root/'iosApp']
    if any(output_dir==p or output_dir.is_relative_to(p) or trace_path.is_relative_to(p) for p in protected):fail('outputs','use a staging/build directory, not live source/content paths')
    all_inputs={*inputs.values(),manifest_path}
    if trace_path in all_inputs or trace_path.suffix == '.kt' or any(p.is_relative_to(output_dir) for p in all_inputs):fail('outputs','input/output paths must not overlap')
    payloads={k:read_json(p) for k,p in inputs.items()}
    manifest=read_json(manifest_path)
    if not isinstance(manifest,dict) or not isinstance(manifest.get('payloads'),list) or not all(isinstance(r,dict) and isinstance(r.get('file'),dict) for r in manifest['payloads']):
        fail('manifest/payloads','expected typed manifest object with file records')
    records=manifest['payloads']
    for key,path in inputs.items():
        if not path.is_relative_to(root):fail(str(path),'authoring inputs must be inside the repository root')
        matches=[r for r in records if r.get('kind')==key]
        expected={'path':path.relative_to(root).as_posix(),'sha256':file_sha(path)}
        if matches!=[{'kind':key,'file':expected}]:fail('manifest/payloads',f'exactly one matching {key} payload required')
    if any(p.get('kind') not in {*ROOT_TYPES,'asset'} for p in records):fail('manifest/payloads','unknown payload kind')
    validator=Validator(root,source_authority)
    totals=validator.package(payloads,manifest,profile)
    package={'manifest':manifest,**payloads}
    # Kotlin field name is legacyAliases, not the JSON root spelling used by the CLI.
    emitter=Emitter(validator.schema,symbol)
    mapping={'manifest':str(manifest_path.relative_to(root))+'#',**{k:str(p.relative_to(root))+'#' for k,p in inputs.items()}}
    files=emitter.render(package,mapping)
    output_records=[{'path':name,'sha256':hashlib.sha256(data.encode()).hexdigest()} for name,data in sorted(files.items())]
    trace={'schema_version':1,'profile':profile,'package_identity':manifest['identity'],'outputs':output_records,'records':emitter.trace,'totals':totals}
    data=json.dumps(trace,ensure_ascii=False,sort_keys=True,indent=2)+'\n'
    if trace_path.parent==output_dir and trace_path.name in files:fail('outputs','trace path collides with Kotlin output')
    if trace_path.is_relative_to(root) and str(trace_path.relative_to(root)) in validator.files:
        fail('outputs','trace path overlaps a referenced source/asset/model input')
    if any((root/path).is_relative_to(output_dir) for path in validator.files):
        fail('outputs','Kotlin output directory overlaps a referenced source/asset/model input')
    # Validate ownership of every destination before writing any output.
    existing=list(output_dir.glob('GeneratedCurriculum*.kt')) if output_dir.exists() else []
    for path in existing:
        if not path.read_text().startswith(MARKER):fail(str(path),'refusing to overwrite a non-generated file')
    if trace_path.exists():
        try: old=read_json(trace_path)
        except ContentError:fail(str(trace_path),'refusing to overwrite a non-trace file')
        if old.get('schema_version')!=1 or 'records' not in old or 'outputs' not in old:fail(str(trace_path),'refusing to overwrite a non-trace file')
    output_dir.mkdir(parents=True,exist_ok=True);trace_path.parent.mkdir(parents=True,exist_ok=True)
    for name,content in sorted(files.items()):
        (output_dir/name).write_text(content)
    for path in existing:
        if path.name not in files:path.unlink()
    trace_path.write_text(data)
    return totals
