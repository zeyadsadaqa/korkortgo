"""Build the accepted package separately, retaining the frozen held-candidate audit trail.

Requires exact per-revision delivery decisions and passing native context matrices.
No changes to legacy questions or their historical acceptance receipts.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
from compile_curriculum import ROOT, Validator, Schema, manifest_digest, canonical, kotlin_string
from build_reader import SharedEmitter

BASE = Path('docs/curriculum/app-migration/implementation-evidence/closure-9j-9m-9l14')
DEST = Path('composeApp/src/commonMain/kotlin/se/korkort')
POLICY = Path('content/delivery-targets.json')

def read(path):
    return json.loads((ROOT/path).read_text())

def identity(path):
    return {'path': str(path), 'sha256': hashlib.sha256((ROOT/path).read_bytes()).hexdigest()}

def dump(value):
    return json.dumps(value, ensure_ascii=False, indent=2)+'\n'

def build(check=False):
    decisions_path = BASE/'delivery-acceptance.json'
    decisions = read(decisions_path)
    assert decisions['status'] == 'passed'
    assert decisions['ios_scope'] == 'simulator'
    for record in decisions['inputs']:
        assert identity(Path(record['path'])) == record, record['path']
    decision_rows = {r['question_id']: r for r in decisions['questions']}
    assert len(decision_rows) == 616
    questions = copy.deepcopy(read(Path('content/assessment-questions.json'))['questions'])
    assert len(questions) == 1000
    asset_rows = {r['asset_id']: (i, r) for i, r in enumerate(decisions['assets'])}
    for q in questions:
        if q['acceptance']['eligibility'] != 'held':
            continue
        row = decision_rows[q['key']['question_id']]
        assert row['revision'] == q['key']['revision'] and row['status'] == 'passed'
        semantics = {k: v for k, v in q.items() if k != 'acceptance'}
        assert row['assessment_sha256'] == hashlib.sha256(canonical(semantics)).hexdigest()
        assert row['shared_question_runs'] == 4
        assert row['native_context_evidence'] and row['route_evidence']
        proof = []
        images = list(filter(None, [q['image']]+[o['image'] for o in q['options']]))
        for asset_id in sorted({image['asset_id'] for image in images}):
            index, asset = asset_rows[asset_id]
            assert asset['status'] == 'passed'
            assert set(asset['platforms']) == set(read(POLICY)['required_platforms'])
            proof.append({'record': {'file': identity(decisions_path), 'locator': f'json:/assets/{index}', 'evidence_ids': [], 'pdf_evidence_page': None}, 'reviewed_on': decisions['date']})
        q['acceptance'].update(eligibility='accepted', open_holds=[], delivery_proof=proof)
    outputs = {}
    def output(path, value):
        text = value if isinstance(value, str) else dump(value)
        if check:
            assert (ROOT/path).read_text() == text, path
        else:
            (ROOT/path).parent.mkdir(parents=True, exist_ok=True)
            (ROOT/path).write_text(text)
        outputs[str(path)] = text
    payload = {'schema_version': 1, 'questions': questions}
    question_path = Path('content/accepted-assessment-questions.json')
    output(question_path, payload)
    output(BASE/'accepted-question-parity.tsv', ''.join(q['key']['question_id']+'\t'+hashlib.sha256(canonical(q)).hexdigest()+'\n' for q in questions))
    manifest = copy.deepcopy(read(Path('content/content-manifest.json')))
    manifest['identity']['content_version'] = manifest['source_curriculum']['content_version']+'-accepted-9j'
    by_path = {r['path']: r for r in manifest['inputs']}
    for path in [POLICY, decisions_path, Path('tools/finalize_question_package_9j.py')]:
        by_path[str(path)] = identity(path)
    manifest['inputs'] = list(by_path.values())
    next(r for r in manifest['payloads'] if r['kind']=='questions')['file'] = identity(question_path)
    manifest['question_revisions'] = [{'key': q['key'], 'eligibility': 'accepted'} for q in questions]
    manifest['identity']['manifest_sha256'] = manifest_digest(manifest)
    manifest_path = Path('content/accepted-content-manifest.json')
    output(manifest_path, manifest)
    payloads = {r['kind']: read(Path(r['file']['path'])) for r in manifest['payloads'] if r['kind']!='asset'}
    result = Validator(source_authority='docs/curriculum/app-migration/implementation-evidence/9J/source-authority.json').package(payloads, manifest, 'release')
    emitter = SharedEmitter(Schema(ROOT), 'accepted9J')
    entries = []
    for q in questions:
        if q['key']['question_id'] in decision_rows:
            call = emitter.emit(q['acceptance'], 'AssessmentAcceptance', q['key']['question_id']+'/accepted')
            entries.append(kotlin_string(q['key']['question_id'])+' to '+call)
    chunks = [emitter.function('Map<String, AssessmentAcceptance>', 'mapOf('+', '.join(entries[i:i+20])+')', 'acceptance map', None) for i in range(0,len(entries),20)]
    header = '// Generated by tools/finalize_question_package_9j.py; exact accepted release.\npackage se.korkort\n\n'
    top = header+'private val acceptedDecisions9J by lazy { '+' + '.join(chunks)+' }\n'
    top += 'internal val acceptedQuestions9J: List<AssessmentQuestion> by lazy { candidateQuestions9J.map { q -> q.copy(acceptance = acceptedDecisions9J[q.key.questionId.value] ?: q.acceptance) } }\n'
    top += 'internal val acceptedIdentity9J = ContentPackageIdentity('+kotlin_string(manifest['identity']['content_version'])+', Sha256('+kotlin_string(manifest['identity']['manifest_sha256'])+'))\n'
    top += 'internal val acceptedPracticeBank9J by lazy { PracticeBank(acceptedIdentity9J, acceptedQuestions9J, true) }\n'
    top += f'internal const val acceptedQuestionCount9J = {len(questions)}\n'
    curriculum = payloads['curriculum']
    top += 'internal val acceptedCurriculumSummary9J = CurriculumSummary('+kotlin_string('2026 curriculum')+', '+str(len(curriculum['modules']))+', '+str(sum(len(m['lesson_ids']) for m in curriculum['modules']))+', '+str(len(questions))+', '+str(len(curriculum['sign_entries']))+')\n'
    output(DEST/'AcceptedQuestionPackage9J.kt', top)
    for n in range(0,len(emitter.functions),200):
        output(DEST/f'AcceptedQuestionPackage9JPart{n//200:03}.kt', header+''.join(f'internal fun {name}(): {kind} = {expr}\n' for name,kind,expr in emitter.functions[n:n+200]))
    output(BASE/'release-validation.json', {'date': decisions['date'], 'status': 'passed', 'result': result, 'manifest': identity(manifest_path), 'questions': 1000, 'concepts': 500, 'accepted': 1000, 'held': 0, 'legacy_originals_retained_as_audit_data': True, 'ios_scope': 'simulator'})
    return outputs

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    build(args.check)
    print('9J accepted package: 1,000 questions, no open holds, release validation passed.')
