"""Decode exact held official PDFs into shared, hash-bound vector display lists.
Requires PyMuPDF 1.28.2; rejects unsupported text/images, clipping masks or stroke styles.
"""
import argparse,hashlib,json
from pathlib import Path
import pymupdf as pdf
ROOT=Path(__file__).resolve().parent.parent
CODES=[f'S{n}' for n in range(1,14)]+['T1','T2','T6','T8','T22']
BASE=Path('composeApp/src/commonMain/kotlin/se/korkort')
EVIDENCE=Path('docs/curriculum/app-migration/implementation-evidence/9L10/vector-decoding.json')
def generate():
    assert pdf.VersionBind=='1.28.2'
    assets=json.loads((ROOT/'content/curriculum.json').read_text())['assets'];files={};records=[];lookups=[]
    def f(n):return repr(float(n))+'f'
    def pt(p):return f(p.x)+', '+f(p.y)
    for code in CODES:
        asset=next(a for a in assets if a['code_or_illustration_id']==code);source=asset['bundled'];digest=hashlib.sha256((ROOT/source['path']).read_bytes()).hexdigest();assert digest==source['sha256']==asset['original']['sha256']
        doc=pdf.open(ROOT/source['path']);page=doc[0];assert not page.get_text().strip() and not page.get_images()
        drawings=page.get_drawings(extended=True);clips=[];layers=[];segment_count=0
        for d in drawings:
            clips=[c for c in clips if c['level']<d['level']]
            if d['type']=='clip':clips.append(d);continue
            if d['type']=='group':raise ValueError('Unsupported transparency group')
            if not d['rect'].intersects(page.rect):continue
            assert all(len(c['items'])==1 and c['items'][0][0]=='re' for c in clips)
            clip=(clips[-1]['scissor'] if clips else page.rect) & page.rect
            assert d['type'] in ('s','f')
            fill=d['type']=='f'
            if fill:assert d['fill_opacity']==1
            else:assert d['dashes']=='[] 0' and d['stroke_opacity']==1 and d['lineCap']==(1,1,1) and d['lineJoin']==1
            commands=[];end=None;segment_count+=len(d['items'])
            for item in d['items']:
                op=item[0]
                if op=='qu':
                    q=item[1];commands+=['moveTo('+pt(q.ul)+')','lineTo('+pt(q.ur)+')','lineTo('+pt(q.lr)+')','lineTo('+pt(q.ll)+')','close()'];end=None
                elif op=='re':
                    r=item[1];points=[pdf.Point(r.x0,r.y0),pdf.Point(r.x1,r.y0),pdf.Point(r.x1,r.y1),pdf.Point(r.x0,r.y1)]
                    if item[2]<0:points.reverse()
                    commands+=['moveTo('+pt(points[0])+')']+['lineTo('+pt(p)+')' for p in points[1:]]+['close()'];end=None
                elif op in ('l','c'):
                    if end!=item[1]:commands.append('moveTo('+pt(item[1])+')')
                    commands.append(('lineTo('+pt(item[2])+')') if op=='l' else 'cubicTo('+', '.join(pt(p) for p in item[2:])+')');end=item[-1]
                else:raise ValueError('Unsupported operation '+op)
            if d['closePath']:commands.append('close()')
            colour=d['fill'] if fill else d['color']
            layers.append('ExactVectorDrawing(sourceSha256=Sha256("'+digest+'"), width='+f(page.rect.width)+', height='+f(page.rect.height)+', clip=Rect('+', '.join(f(v) for v in clip)+'), strokeWidth='+f(0 if fill else d['width'])+', colour=Color('+', '.join(f(v) for v in colour)+', 1f), fill='+str(fill).lower()+', evenOdd='+str(bool(d.get('even_odd'))).lower()+', path=Path().apply {\n'+''.join('    '+c+'\n' for c in commands)+'})')
        assert layers
        path=BASE/f'DecodedVector{code}.kt'
        text='// Generated by tools/extract_official_vectors.py from unchanged official PDF bytes.\npackage se.korkort\n\nimport androidx.compose.ui.geometry.Rect\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.graphics.Path\n\ninternal fun decodedVector'+code+'() = ExactVectorPicture(Sha256("'+digest+'"), '+f(page.rect.width)+', '+f(page.rect.height)+', listOf(\n'+',\n'.join(layers)+'\n))\n'
        files[path]=text;lookups.append('    "'+digest+'" -> decodedVector'+code+'()')
        records.append({'code':code,'asset_id':asset['id'],'source':source,'original':asset['original'],'page_dimensions_pt':[page.rect.width,page.rect.height],'visible_layers':len(layers),'source_segments':segment_count,'renderer':{'path':str(path),'sha256':hashlib.sha256(text.encode()).hexdigest()},'geometry_changes':False,'stroke_thickening':False})
    files[BASE/'DecodedOfficialVectors.kt']='// Generated by tools/extract_official_vectors.py; exact decoded drawing cache.\npackage se.korkort\ninternal fun decodedOfficialVector(sha: Sha256): ExactVectorPicture? = when(sha.value) {\n'+'\n'.join(lookups)+'\n    else -> null\n}\ninternal fun decodedS1Vector() = decodedVectorS1().layers.single()\n'
    files[EVIDENCE]=json.dumps({'decoder':'PyMuPDF '+pdf.VersionBind,'records':records,'delivery_acceptance':'Not conferred by decoder generation; actual target delivery remains required.'},indent=2)+'\n'
    return files

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for path,value in generate().items():
        if args.check:assert (ROOT/path).read_text()==value,path
        else:(ROOT/path).parent.mkdir(parents=True,exist_ok=True);(ROOT/path).write_text(value)
if __name__=='__main__':main()
